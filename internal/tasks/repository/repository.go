package repository

import (
	"database/sql"
	"fmt"
	"os"
	"time"

	"taskTitle/internal/tasks/models"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/stdlib"
)

type DB struct {
	db *sql.DB
}

type Repository interface {
	ReadDB() (table []models.Table, err error)
	CreateDB(name, text string) (int64, error)
	DeleteDB(id int) error
	HealthDB() error
}

func NewRepository(db *sql.DB) Repository {
	return &DB{db: db}
}

func OpenDB() (*sql.DB, error) {
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		dsn = "postgres://notes:notes@127.0.0.1:5433/notes?sslmode=disable"
	}

	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		return nil, err
	}

	db := stdlib.OpenDB(*cfg)

	var pingErr error
	deadline := time.Now().Add(30 * time.Second)
	for {
		pingErr = db.Ping()
		if pingErr == nil || time.Now().After(deadline) {
			break
		}
		time.Sleep(time.Second)
	}
	if pingErr != nil {
		db.Close()
		return nil, pingErr
	}

	return db, nil
}

func (db *DB) ReadDB() (table []models.Table, err error) {
	rows, err := db.db.Query("SELECT id, name, text FROM notes")
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	for rows.Next() {
		var t models.Table
		if err := rows.Scan(&t.Id, &t.Name, &t.Text); err != nil {
			return nil, err
		}

		table = append(table, t)
	}

	if err := rows.Err(); err != nil {
		return nil, err
	}

	return table, nil
}

func (db *DB) CreateDB(name, text string) (int64, error) {
	var id int64
	err := db.db.QueryRow(
		"INSERT INTO notes (name, text) VALUES ($1, $2) RETURNING id",
		name, text,
	).Scan(&id)
	if err != nil {
		return 0, err
	}
	return id, nil
}

func (db *DB) DeleteDB(id int) error {
	res, err := db.db.Exec("DELETE FROM notes WHERE id = $1", id)
	if err != nil {
		return err
	}
	n, _ := res.RowsAffected()
	if n == 0 {
		return fmt.Errorf("заметка %d не найдена", id)
	}
	return nil
}

func (db *DB) HealthDB() error {
	return db.db.Ping()
}

func InitSchemaTask(db *sql.DB) error {
	_, err := db.Exec(`CREATE TABLE IF NOT EXISTS notes (
		id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		name TEXT NOT NULL,
		text TEXT NOT NULL
	)`)
	return err
}
